#!/usr/bin/env python3
"""Build review/inbound-links.md: where to add each planned inbound link on the live site.

For every article's `inbound_links` (source page + anchor), fetch the live source page,
pick the H2 section whose text best matches the target article's keywords, and write a
ready-to-paste sentence. Also flags source pages that already link to the target.
"""
import html as htmllib
import re
import subprocess
from collections import defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
UA = "Mozilla/5.0 (Macintosh; Intel Mac OS X 14_0) AppleWebKit/537.36 Chrome/128 Safari/537.36"
STOP = set("a an the for of to in on and vs with how what is are your you our best free 2026 us".split())


def fetch(url):
    for _ in range(3):  # pages occasionally time out; retry before giving up
        page = subprocess.run(["curl", "-sL", "-m", "40", "-A", UA, url],
                              capture_output=True).stdout.decode("utf-8", "ignore")
        if page:
            return page
    return ""


def sections(page):
    page = re.sub(r"(?is)<(script|style|nav|footer|header)[^>]*>.*?</\1>", " ", page)
    parts = re.split(r"(?is)<h2[^>]*>(.*?)</h2>", page)
    out = [("(intro)", parts[0])]
    for i in range(1, len(parts), 2):
        out.append((parts[i], parts[i + 1] if i + 1 < len(parts) else ""))
    clean = lambda t: htmllib.unescape(re.sub(r"\s+", " ", re.sub(r"(?s)<[^>]+>", " ", t))).strip()
    return [(clean(h), clean(b)) for h, b in out]


def toks(t):
    return {w for w in re.findall(r"[a-z0-9]+", t.lower()) if w not in STOP and len(w) > 2}


def main():
    plan = defaultdict(list)
    for p in sorted((ROOT / "articles").glob("*.md")):
        fm = yaml.safe_load(p.read_text().split("---\n", 2)[1])
        target = f"https://lynkk.ai/blog/{fm['slug']}"
        topic = toks(" ".join([fm["primary_keyword"], fm["title"]] + fm["secondary_keywords"]))
        for link in fm["inbound_links"]:
            plan[link["from"]].append((target, link["anchor"], topic, fm["title"]))
    lines = ["# Inbound link plan", "",
             "Generated by `tools/inbound_sheet.py` from each article's `inbound_links` and the live source pages "
             "(fetched 18 October 2026). Add each sentence at the end of the named section on the source page "
             "once the target article is live, then tick the box.", "",
             "| Done | Source page | Section to edit | Sentence to add (links the target) |",
             "|---|---|---|---|"]
    missing = []
    for src in sorted(plan):
        page = fetch(src)
        if "<title>Page not found" in page or not page:
            missing.append(src)
            continue
        secs = sections(page)
        for target, anchor, topic, title in plan[src]:
            already = target in page
            body_secs = [x for x in secs if not re.match(r"\(intro\)|faq|frequently|conclusion|final", x[0], re.I)]
            best = max(body_secs or secs, key=lambda s: len(topic & toks(s[0] + " " + s[1][:3000])))
            section = best[0][:70] or "(intro)"
            sentence = f"For more, see our guide to [{anchor}]({target})."
            note = " (already linked)" if already else ""
            lines.append(f"| [ ] | {src.replace('https://lynkk.ai', '')} | {section}{note} | {sentence} |")
    if missing:
        lines += ["", "Source pages that did not load: " + ", ".join(missing)]
    (ROOT / "review" / "inbound-links.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{sum(len(v) for v in plan.values())} links across {len(plan)} source pages; missing: {missing or 'none'}")


if __name__ == "__main__":
    main()
